volatile uint8_t g_usb_light_last_frame[CH340_HOST_FRAME_LEN];

fsp_err_t usb_light_set(usb_light_mode_t mode)
{
    uint8_t   frame[CH340_HOST_FRAME_LEN];
    fsp_err_t err;

    if (mode >= (sizeof(g_usb_light_frames) / sizeof(g_usb_light_frames[0])))
    {
        return FSP_ERR_INVALID_ARGUMENT;
    }

    if (!ch340_host_is_ready())
    {
        return FSP_ERR_INVALID_STATE;
    }

    memcpy(frame, g_usb_light_frames[mode], CH340_HOST_FRAME_LEN);
    memcpy((void *) g_usb_light_last_frame, frame, CH340_HOST_FRAME_LEN);

    err = ch340_host_write(frame, CH340_HOST_FRAME_LEN);

    return err;
}
